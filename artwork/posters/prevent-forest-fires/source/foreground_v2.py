def _cut_edge(d, seed, rough=1.05):
    """Carve small bark notches into authored straight spans, keeping curves.

    A notch has a shoulder, a torn tip and an uneven return. Their irregular
    spacing follows one continuous wood edge, rather than random polygons.
    """
    token=re.findall(r'[MLCQZmlcqz]|-?\d*\.?\d+(?:[eE][+-]?\d+)?',d)
    rng=Random(seed);out=[];i=0;command=None;current=None;start=None
    sizes={'M':2,'L':2,'C':6,'Q':4}
    while i<len(token):
        if token[i].isalpha():command=token[i].upper();i+=1
        if command=='Z':
            out.append('Z');current=start;command=None;continue
        n=sizes[command];vals=list(map(float,token[i:i+n]));i+=n
        target=(vals[-2],vals[-1])
        if command=='L' and current:
            dx,dy=target[0]-current[0],target[1]-current[1];ll=hypot(dx,dy)
            if ll>5:
                nx,ny=-dy/ll,dx/ll;segments=max(1,int(ll/rng.uniform(4,7)))
                for k in range(1,segments):
                    t=k/segments;offset=rng.uniform(-rough,rough)
                    if rng.random()<.18:offset*=1.8
                    x=current[0]+dx*t+nx*offset;y=current[1]+dy*t+ny*offset
                    out.append(f'L{x:.2f} {y:.2f}')
            out.append(f'L{target[0]:.2f} {target[1]:.2f}')
        else:
            out.append(command+' '.join(f'{v:.2f}' for v in vals))
        current=target
        if command=='M':start=current;command='L'
    return ' '.join(out)


