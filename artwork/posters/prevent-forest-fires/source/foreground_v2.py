def _brush_cut(x, y, dx, dy, length, width, bend, fill):
    """Small tapered, slightly asymmetric carving; the tip follows wood grain."""
    ll=hypot(dx,dy); ux,uy=dx/ll,dy/ll; nx,ny=-uy,ux
    def xy(u,v): return f'{x+ux*u+nx*v:.2f} {y+uy*u+ny*v:.2f}'
    d=(f'M{xy(0,0)} C{xy(length*.22,width)} {xy(length*.54,bend+width*.65)} {xy(length,0)} '
       f'C{xy(length*.65,bend-width*.40)} {xy(length*.21,-width*.42)} {xy(0,0)} Z')
    return p(d,fill)


def _grain_along(points, seed, count, spread, color=WOOD, strength=.65, run_scale=1.0):
    """Vary length, placement, and curvature along an authored physical axis.

    Most gouges are short; a few are longer and follow a knot or grain sweep.
    Their cross-axis spread varies in clumps, preventing a ruled-line pattern.
    """
    rng=Random(seed); lengths=[]; total=0
    for a,b in zip(points,points[1:]):
        ll=hypot(b[0]-a[0],b[1]-a[1]);lengths.append(ll);total+=ll
    out=[]
    for i in range(count):
        at=rng.random()*total;seg=0
        while seg<len(lengths)-1 and at>lengths[seg]:at-=lengths[seg];seg+=1
        a,b=points[seg],points[seg+1];ll=lengths[seg]
        ux,uy=(b[0]-a[0])/ll,(b[1]-a[1])/ll;nx,ny=-uy,ux
        t=at/ll;off=rng.uniform(-spread,spread)*(rng.uniform(.2,1.0))
        x=a[0]+(b[0]-a[0])*t+nx*off;y=a[1]+(b[1]-a[1])*t+ny*off
        run=(rng.uniform(3.0,14.0) if rng.random()<.78 else rng.uniform(16,34))*run_scale
        wid=rng.uniform(.24,1.05)*strength
        out.append(_brush_cut(x,y,ux,uy,run,wid,rng.uniform(-.7,.7),color))
    return ''.join(out)


