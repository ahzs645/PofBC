def authored_bark_gouge(d,fill,i,j):
    """Long grain fibers inside a designed wound, not a solid coloured chip."""
    import re
    nums=list(map(float,re.findall(r'[-+]?(?:[0-9]*\.)?[0-9]+',d)))
    xs=nums[::2];ys=nums[1::2];x0=min(xs);x1=max(xs);y0=min(ys);y1=max(ys)
    if fill==YELLOW:
        # Narrow light ridges keep the exposed core subordinate to the wood.
        cx=(x0+x1)/2;cy=(y0+y1)/2
        dd=_design_points(d,lambda x,y:(cx+(x-cx)*(.70 if y1-y0>x1-x0 else 1),cy+(y-cy)*(.78 if x1-x0>=y1-y0 else 1)))
        return path(contour(dd,91000+i*100+j,.10,1),fill,id=f'canopy-bark-gouge-{i}-{j}')
    clip=f'canopy-bark-gouge-window-{i}-{j}'
    out=[f'<defs><clipPath id="{clip}">'+path(d)+'</clipPath></defs>',f'<g clip-path="url(#{clip})">']
    rng=Random(81000+i*100+j)
    if y1-y0>=x1-x0:
        n=max(3,ceil((x1-x0)/.85))
        for k in range(n):
            xx=x0+(k+.45)*(x1-x0)/n
            yy=y0+rng.uniform(-.8,(y1-y0)*.12);ey=y1-rng.uniform(-.4,(y1-y0)*.13)
            out.append(bark_fiber(xx,yy,xx+rng.uniform(-.6,.6),(yy+ey)/2,xx+rng.uniform(-.5,.5),ey,rng.uniform(.28,.58),ORANGE))
    else:
        n=max(3,ceil((y1-y0)/.75))
        for k in range(n):
            yy=y0+(k+.4)*(y1-y0)/n;ww=rng.uniform(.27,.55)
            xx=x0+rng.uniform(-.5,(x1-x0)*.13);ex=x1-rng.uniform(-.5,(x1-x0)*.12)
            out.append(path(f'M {xx:.2f},{yy:.2f} Q {(xx+ex)/2:.2f},{yy-ww:.2f} {ex:.2f},{yy+.4:.2f} L {ex-.7:.2f},{yy+ww:.2f} Q {(xx+ex)/2:.2f},{yy+ww:.2f} {xx:.2f},{yy+.3:.2f} Z',ORANGE))
    out.append('</g>')
    return ''.join(out)

def scale_fan(x,y,length,angle,width,seed):
    """A short woody twig carrying a few unequal pointed needle scales."""
    rng=Random(seed);a=angle*pi/180;ca=cos(a);sa=sin(a)
    def p(u,v):return (x+u*ca-v*sa,y+u*sa+v*ca)
    out=[]
    # The central curved woody sliver makes every scale structurally attached.
    out.append(poly([p(0,-.65),p(length*.44,-.5),p(length,0),p(length*.38,.8),p(0,.65)]))
    count=rng.randint(3,5)
    for i in range(count):
        u=length*(i+.7)/(count+.7)
        side=-1 if i%2 else 1
        vv=width*rng.uniform(.52,1.05)*side
        ww=length/count*rng.uniform(.7,1.2)
        a1=p(u-ww*.6,0);a2=p(u-ww*.35,vv*.7);a3=p(u+ww*.65,vv);a4=p(u+ww*.2,vv*.32);a5=p(u+ww*.75,0)
        out.append(path(f'M {a1[0]:.2f},{a1[1]:.2f} Q {a2[0]:.2f},{a2[1]:.2f} {a3[0]:.2f},{a3[1]:.2f} L {a4[0]:.2f},{a4[1]:.2f} {a5[0]:.2f},{a5[1]:.2f} Z'))
    return ''.join(out)

