def contour(d,seed,roughness=.72,smoothing=2,return_points=False):
    """Turn authored silhouette guides into irregular cut-wood curves.

    This operates only on the manually entered vector design. Short asymmetric
    knife facets subdivide broad edges, while corner rounding avoids the blocky
    polygon appearance that does not match the original print.
    """
    import re
    tok=re.findall(r'[MLQCZmlqcz]|[-+]?(?:[0-9]*\.)?[0-9]+',d)
    i=0;cmd=None;p=(0.,0.);start=None;pts=[]
    def sample(kind,values):
        nonlocal p,start
        end=(values[-2],values[-1])
        controls=[p]+[(values[k],values[k+1]) for k in range(0,len(values),2)]
        ll=sum(hypot(controls[k+1][0]-controls[k][0],controls[k+1][1]-controls[k][1]) for k in range(len(controls)-1))
        n=max(1,ceil(ll/1.65))
        for j in range(n):
            t=j/n;u=1-t
            if kind=='L':x=u*p[0]+t*end[0];y=u*p[1]+t*end[1]
            elif kind=='Q':
                cx,cy=values[:2];x=u*u*p[0]+2*u*t*cx+t*t*end[0];y=u*u*p[1]+2*u*t*cy+t*t*end[1]
            else:
                a,b,c,e=values[:4];x=u**3*p[0]+3*u*u*t*a+3*u*t*t*c+t**3*end[0];y=u**3*p[1]+3*u*u*t*b+3*u*t*t*e+t**3*end[1]
            pts.append((x,y))
        p=end
    while i<len(tok):
        if tok[i].isalpha():cmd=tok[i];i+=1
        if cmd=='Z':
            sample('L',list(start));cmd=None;continue
        n={'M':2,'L':2,'Q':4,'C':6}[cmd]
        vv=list(map(float,tok[i:i+n]));i+=n
        if cmd=='M':p=tuple(vv);start=p;cmd='L'
        else:sample(cmd,vv)
    N=len(pts)
    for z in range(smoothing):
        pts=[((pts[i-1][0]+2*pts[i][0]+pts[(i+1)%N][0])/4,(pts[i-1][1]+2*pts[i][1]+pts[(i+1)%N][1])/4) for i in range(N)]
    if return_points:return pts
    rng=Random(seed);cut=[]
    for i,(x,y) in enumerate(pts):
        ax,ay=pts[i-1];bx,by=pts[(i+1)%N];dx=bx-ax;dy=by-ay;ll=hypot(dx,dy) or 1
        off=rng.uniform(-roughness,roughness)*(1.7 if i%13==0 else 1)
        cut.append((x-dy/ll*off,y+dx/ll*off))
    a=cut[-1];b=cut[0];out=f'M {(a[0]+b[0])/2:.2f},{(a[1]+b[1])/2:.2f}'
    for i,(x,y) in enumerate(cut):
        bx,by=cut[(i+1)%N];out+=f' Q {x:.2f},{y:.2f} {(x+bx)/2:.2f},{(y+by)/2:.2f}'
    return out+' Z'

