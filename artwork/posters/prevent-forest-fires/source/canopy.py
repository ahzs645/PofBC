def boundary_foliage(d,seed,tree_axis=None):
    """Articulate the authored bough borders with small evergreen twigs."""
    pts=contour(d,seed,0,2,True);N=len(pts);rng=Random(seed);out=[]
    area=sum(pts[i][0]*pts[(i+1)%N][1]-pts[(i+1)%N][0]*pts[i][1] for i in range(N))
    sign=1 if area>0 else -1
    for i in range(0,N,10):
        if rng.random()<.15:continue
        x,y=pts[i]
        if tree_axis is not None and abs(x-tree_axis)<3.8:continue
        ax,ay=pts[i-1];bx,by=pts[(i+1)%N];dx=bx-ax;dy=by-ay;ll=hypot(dx,dy) or 1
        nx=sign*dy/ll;ny=-sign*dx/ll
        # Mix the outer-normal direction with the downward hang of conifer
        # needles; upperside tips are smaller and sparser.
        if ny<.20:continue
        from math import atan2
        angle=atan2(ny+.65,nx*.75)*180/pi+rng.uniform(-27,27)
        length=rng.uniform(7,13)*(1 if tree_axis is not None else 1.25)
        width=rng.uniform(2.4,4.6)
        out.append(needle_tuft(x-nx*.6,y-ny*.6,length,angle,width,seed*10000+i))
    return ''.join(out)

