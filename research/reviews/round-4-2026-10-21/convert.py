"""Brings Round 4 (21 October 2026) into the history, from the reviewed proposals in integration/.

Run from the repository root:  python3 -I research/reviews/round-4-2026-10-21/local_register.py
then                            python3 -I research/reviews/round-4-2026-10-21/convert.py
then                            python3 -I research/reviews/institutional-history-2026-10-21/convert.py
and                             npm run build:government

Each module of the handback (branches, crowns, health, root) was read against the repository and
its claims turned into the history's own shapes, one proposal per module (integration/<module>.json,
with the reasoning in <module>-notes.md). This script applies them:

- every proposed event goes into research/atlas/events-round4.json;
- the one new body (the British Columbia Harbours Board) into research/history/bodies-round4.json;
- corrections to hand-kept files (bodies.json, responsible-*.json, events-crowns.json,
  events-divisions.json) are made in place, each only if the file still holds the value the
  proposal says it corrects, or already holds the new one;
- corrections to files another converter writes (bodies-health-lineage.json,
  events-institutional-history.json) go into overrides.json, which that converter applies.

The sub-agency records are not written here: they go through `npm run research:merge` (see
INTEGRATION.md), which checks them against the evidence rules. Nothing a proposal lists under
not_applied is touched.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
RESEARCH = ROOT / 'research'
MODULES = ['branches', 'crowns', 'health', 'root', 'carried', 'review']
# Files another converter writes: Round 4 only tells that converter what to change.
GENERATED = {'history/bodies-health-lineage.json', 'atlas/events-institutional-history.json'}

proposals = {m: json.loads((HERE / 'integration' / f'{m}.json').read_text()) for m in MODULES if (HERE / 'integration' / f'{m}.json').exists()}


STYLE = {}


def read(rel):
    """A research file, remembering how it is laid out so that writing it back changes only what changed."""
    text = (RESEARCH / rel).read_text()
    second = text.split('\n')[1] if '\n' in text else ''
    STYLE[rel] = (max(1, len(second) - len(second.lstrip(' '))), '\n' if text.endswith('\n') else '')
    return json.loads(text)


def write(rel, data):
    indent, end = STYLE.get(rel, (2, '\n'))
    (RESEARCH / rel).write_text(json.dumps(data, indent=indent, ensure_ascii=False) + end)


def rel_of(file):
    return file.removeprefix('research/')


# ── Events ──────────────────────────────────────────────────────────────────────────────────────

events = [event for p in proposals.values() for event in p.get('events', [])]
# The local bodies an event acts on (research/history/local-hospital-districts.json, written by
# local_register.py, run first): every district whose research claims the event's claims name is a
# related subject, so the event is found from the district as well as from the ministry.
LOCAL = RESEARCH / 'history/local-hospital-districts.json'
if LOCAL.exists():
    local = json.loads(LOCAL.read_text())['records']
    for event in events:
        named = set(event.get('round4_claims', []))
        districts = [record['id'] for record in local if named & set(record.get('claims', []))]
        if districts:
            event['related_subject_ids'] = list(dict.fromkeys([*event.get('related_subject_ids', []), *districts]))
ids = [event['id'] for event in events]
assert len(ids) == len(set(ids)), 'duplicate Round 4 event ids'
held = {e['id'] for f in (RESEARCH / 'atlas').glob('events-*.json') if f.name != 'events-round4.json' for e in json.loads(f.read_text()).get('events', [])}
assert not held & set(ids), f'Round 4 events already held: {sorted(held & set(ids))}'
write('atlas/events-round4.json', {
    'metadata': {
        'title': 'Round 4: branches and office families, Crown corporations, the regional health system, hospital districts and the health statutes',
        'as_of': '2026-10-21',
        'produced_by': 'research/reviews/round-4-2026-10-21/convert.py',
        'conventions': {'date_precision': 'kept as stated by the source; a year is never 1 January'},
    },
    'events': events,
})

# ── New bodies ──────────────────────────────────────────────────────────────────────────────────

new_bodies = [body for p in proposals.values() for body in p.get('new_bodies', [])]
write('history/bodies-round4.json', {
    'note': ('Bodies added by Round 4 (research/reviews/round-4-2026-10-21). Generated by its convert.py: '
             'edit the proposals in integration/ and re-run, not this file.'),
    'records': new_bodies,
})

# ── Corrections ─────────────────────────────────────────────────────────────────────────────────

overrides = {}


def same(held, said):
    # A proposal may quote a long old value only as far as "...".
    if isinstance(said, str) and said.endswith('...') and isinstance(held, str):
        return held.startswith(said[:-3].rstrip())
    return held == said


def matches(row, old, new):
    """Whether a row still holds what the proposal corrects (or already holds the correction)."""
    return all(same(row.get(k), v) for k, v in old.items()) or all(row.get(k) == v for k, v in new.items())


def correct(rel, row_id, old, new, remove=()):
    if rel in GENERATED:
        overrides.setdefault(rel, {})[row_id] = {'set': new, **({'remove': list(remove)} if remove else {})}
        return
    data = read(rel)
    rows = data['records'] if 'records' in data else data['events']
    row = next((r for r in rows if r.get('id') == row_id), None)
    assert row is not None, f'{rel} has no {row_id}'
    comparable = {k: v for k, v in old.items() if k != 'responsible'}
    assert matches(row, comparable, {k: v for k, v in new.items() if k in comparable}), f'{rel}#{row_id} no longer holds what Round 4 corrects'
    row.update(new)
    for field in remove:
        row.pop(field, None)
    write(rel, data)


def body_file(body_id):
    for f in sorted((RESEARCH / 'history').glob('bodies*.json')):
        if f.name == 'bodies-round4.json':
            continue
        if any(r['id'] == body_id for r in json.loads(f.read_text())['records']):
            return f'history/{f.name}'
    raise SystemExit(f'no body {body_id}')


def responsible_file(body_id):
    for f in sorted((RESEARCH / 'history').glob('responsible-*.json')):
        if body_id in json.loads(f.read_text())['records']:
            return f'history/{f.name}'
    return None


def set_responsible(body_id, rows):
    """Replace a body's periods where they are kept: its responsible-*.json entry, or its record.
    A proposal's `responsible` is the body's whole list of periods, not an addition to it."""
    rel = responsible_file(body_id)
    if rel is None:
        return False
    data = read(rel)
    data['records'][body_id] = rows
    write(rel, data)
    return True


def remove_responsible(body_id, rows):
    for row in rows:
        rel = rel_of(row['file']) if row['file'].startswith('research/') else row['file']
        data = read(rel)
        rows_held = data['records'].get(body_id, [])
        data['records'][body_id] = [r for r in rows_held if not (r['ministry'] == row['ministry'] and str(r.get('from')) == str(row['from']))]
        write(rel, data)


# Several modules may correct one record (the crowns module dated MTOC's end; the integration review
# then made it an operational transfer): their changes are composed in module order, the later
# winning, and the record is checked once against the value the first one corrects.
composed = {}
for p in proposals.values():
    for change in p.get('body_changes', []):
        key = (change.get('file'), change['id'])
        if key not in composed:
            composed[key] = {**change, 'set': dict(change.get('set', {})), 'remove': list(change.get('remove', []))}
            continue
        held = composed[key]
        held['set'].update(change.get('set', {}))
        held['remove'] = [field for field in dict.fromkeys(held['remove'] + list(change.get('remove', []))) if field not in change.get('set', {})]
        for field in change.get('remove', []):
            held['set'].pop(field, None)

for p in [{'body_changes': list(composed.values())}, *[{'event_corrections': p.get('event_corrections', [])} for p in proposals.values()]]:
    for change in p.get('body_changes', []):
        new = dict(change.get('set', {}))
        responsible = new.pop('responsible', None)
        removed = new.pop('responsible_remove', None)
        rel = rel_of(change['file']) if change.get('file') else body_file(change['id'])
        if removed:
            remove_responsible(change['id'], removed)
        if responsible is not None and rel not in GENERATED and set_responsible(change['id'], responsible):
            pass
        elif responsible is not None:
            new['responsible'] = responsible
        correct(rel, change['id'], change.get('old', {}), new, change.get('remove', []))
    for fix in p.get('event_corrections', []):
        correct(rel_of(fix['file']), fix.get('event_id') or fix['id'], fix.get('old', {}), fix['new'])

# Contemporary signatures that corroborate a minister's term (not a tenure of their own).
for p in proposals.values():
    for change in p.get('data_changes', []):
        rel = rel_of(change['file'])
        data = read(rel)
        term = data['records'][change['record_index']]
        assert all(str(term.get(k)) == str(v) for k, v in change['match'].items()), f'{rel}#{change["record_index"]} is not the term Round 4 names'
        held = term.setdefault('corroborating_evidence', [])
        for row in change.get('add_corroborating_evidence', []):
            if row not in held:
                held.append(row)
        write(rel, data)

(HERE / 'overrides.json').write_text(json.dumps({
    '_note': ('Round 4 changes to files other converters write, applied by them. Generated by this folder\'s '
              'convert.py from integration/: do not edit.'),
    **overrides,
}, indent=2, ensure_ascii=False) + '\n')

# ── Decisions ───────────────────────────────────────────────────────────────────────────────────

decisions = read('decisions.json')
held_decisions = {d['id']: i for i, d in enumerate(decisions['decisions'])}
for p in proposals.values():
    for decision in p.get('decisions', []):
        if decision['id'] in held_decisions:
            decisions['decisions'][held_decisions[decision['id']]] = decision
        else:
            decisions['decisions'].append(decision)
write('decisions.json', decisions)

counts = {m: len(p.get('events', [])) for m, p in proposals.items()}
print(f'{len(events)} events {counts}, {len(new_bodies)} new bodies, '
      f'{sum(len(v) for v in overrides.values())} overrides for other converters')
