/** A poster's parts with their stories attached. Every part must have one: a story that skips a part cannot be read through. */
export const withStories = (posterId, parts) => Object.fromEntries(Object.entries(parts).map(([id, part]) => {
  const story = STORIES[posterId]?.[id]
  if (!story) throw new Error(`No story for ${posterId}/${id}`)
  return [id, { ...part, story }]
}))
