export const withVerifiedSourceColours = (bodies) => bodies.map((body) => {
  const match = reviewedVectors[body.id]
  if (!match) return body
  const { alternates = [], ...vector } = match
  const assets = body.assets.map((asset) => asset.id === vector.variantOf
    ? { ...asset, versionLabel: asset.versionLabel ?? 'Published image', preferredVector: vector.id }
    : asset)
  const versions = [vector, ...alternates].map((version) => ({
    format: 'svg', isVector: true, containsRaster: false, reconstruction: false,
    observedDate: '2026-11-27', ...version
  }))
  return { ...body, assets: [...assets, ...versions] }
})
