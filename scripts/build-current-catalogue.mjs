// Writes the official ministry wording, with the line breaks the Province set it with.
//
// The published marks are hand-broken — their widest body line runs from 2.3 em to 12.3 em — so no
// wrap measure reproduces them. Carrying the breaks as newlines in the text does, exactly, and it
// costs a couple of kilobytes against the megabyte of outlines they replace. Anyone editing a name
// gets the same control: a newline is a line break.
//
// Run: npm run build:current-catalogue

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { nameLines } from '../src/current/currentLayout.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const fitPath = resolve(root, 'scripts/current-fit.json')
if (!existsSync(fitPath)) {
  console.error('\nRun `npm run verify:current-names` first.\n')
  process.exit(1)
}

const { marks } = JSON.parse(readFileSync(fitPath, 'utf8'))
const index = JSON.parse(readFileSync(resolve(root, 'public/current-marks/index.json'), 'utf8'))

const ministries = []
const wrapped = []

for (const ministry of index.ministries) {
  const code = ministry.code
  const entry = { code }

  for (const language of ['en', 'fr']) {
    const fitted = marks[`${code.toLowerCase()}-${language}`]
    // A file can extract cleanly and still hold the wrong wording: one English mark carries the
    // French name, and it fits perfectly, because it is perfectly good French. The language of what
    // was recovered has to be checked, not just the quality of the fit.
    const expected = language === 'en' ? /^Ministry\b/ : /^Ministère\b/
    if (fitted && expected.test(fitted.lines.join(' '))) {
      entry[language] = fitted.lines.join('\n')
      continue
    }

    // Three English files merged two lockups during extraction and one carries the French wording,
    // so their published line breaks are not recoverable. The catalogue name is right; only the
    // breaks are this project's guess, and saying which is more use than hiding it.
    const name = language === 'en'
      // The catalogue has a stray non-breaking space in one entry.
      ? `Ministry of ${ministry.name}`.replace(/ /g, ' ')
      : null
    if (!name) continue
    entry[language] = nameLines(name).join('\n')
    wrapped.push(`${code.toLowerCase()}-${language}`)
  }

  ministries.push(entry)
}

const missingFrench = ministries.filter((m) => !m.fr).map((m) => m.code)

writeFileSync(resolve(root, 'src/current/ministries.js'), `// Generated by scripts/build-current-catalogue.mjs — do not edit.
//
// The Province's ministries and the exact wording of their marks, in both languages. Newlines are
// the line breaks the published artwork uses: it is hand-broken, not wrapped to a measure, so the
// breaks are part of the wording rather than something a layout rule can rediscover.
//
// The wording was read back off the published outlines themselves — see
// scripts/recover_current_names.py — which is also how the French names got here, since the
// Province publishes them only as artwork.

export const MINISTRIES = [
${ministries.map((m) => `  ${JSON.stringify(m)}`).join(',\n')}
]

/** Marks whose published line breaks could not be read, and are wrapped by this project instead. */
export const WRAPPED_BY_US = ${JSON.stringify(wrapped)}

export const MINISTRY_CODES = MINISTRIES.map((ministry) => ministry.code)

/** One ministry's wording, or undefined. Codes are matched case-insensitively. */
export const findMinistry = (code) => MINISTRIES
  .find((ministry) => ministry.code.toLowerCase() === String(code).toLowerCase())
`)

const bytes = JSON.stringify(ministries).length
console.log(`  catalogue   ${ministries.length} ministries, ` +
  `${ministries.filter((m) => m.fr).length} with French wording   ${(bytes / 1024).toFixed(1)} KB`)
if (wrapped.length) console.log(`  wrapped by us (breaks not recoverable): ${wrapped.join(', ')}`)
if (missingFrench.length) console.log(`  no French wording: ${missingFrench.join(', ')}`)
console.log('  → src/current/ministries.js')
