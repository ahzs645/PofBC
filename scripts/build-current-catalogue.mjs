// Writes the official ministry wording, and checks it against the rules that break it.
//
// The Province's marks break their names by hand, but not arbitrarily: four rules read off all 46
// of them — see nameLines in src/current/currentLayout.js — reproduce 44 exactly. So the catalogue
// holds plain wording and lets those rules do the breaking, which is what makes wording typed by
// hand behave like the published kind.
//
// Where a mark genuinely disagrees with its own rules, the wording here carries the Province's
// breaks as newlines and this says which. Two marks do.
//
// Run: npm run build:current-catalogue

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { nameLines } from '../src/current/currentLayout.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const fitPath = resolve(root, 'scripts/current-fit.json')
if (!existsSync(fitPath)) {
  console.error('\nRun `npm run verify:current-names` first.\n')
  process.exit(1)
}

const { marks, labelled = {} } = JSON.parse(readFileSync(fitPath, 'utf8'))
const index = JSON.parse(readFileSync(resolve(root, 'public/current-marks/index.json'), 'utf8'))

const ministries = []
const exceptions = []
const unverified = []

for (const ministry of index.ministries) {
  const code = ministry.code
  const entry = { code }

  for (const language of ['en', 'fr']) {
    // What the Province actually published, in order of authority: the artwork itself, then — for
    // the three English marks whose artwork merged two lockups — the PDF's own text layer, which
    // lists every English name with the breaks its artwork uses.
    const fitted = marks[`${code.toLowerCase()}-${language}`]
    const expected = language === 'en' ? /^Ministry\b/ : /^Ministère\b/
    let published = fitted && expected.test(fitted.lines.join(' ')) ? fitted.lines : null

    if (!published && language === 'en' && labelled[code]) {
      published = ['Ministry of', ...labelled[code]]
    }
    if (!published) {
      if (language === 'en') {
        published = nameLines(`Ministry of ${ministry.name}`.replace(/ /g, ' '), { language })
        unverified.push(`${code.toLowerCase()}-${language}`)
      }
      if (!published) continue
    }

    // Does the rule already break it this way? Then the wording needs no breaks of its own.
    const plain = published.join(' ')
    const byRule = nameLines(plain, { language })
    if (byRule.join('\n') === published.join('\n')) {
      entry[language] = plain
    } else {
      entry[language] = published.join('\n')
      exceptions.push({
        key: `${code.toLowerCase()}-${language}`,
        published: published.slice(1),
        byRule: byRule.slice(1)
      })
    }
  }

  ministries.push(entry)
}

writeFileSync(resolve(root, 'src/current/ministries.js'), `// Generated by scripts/build-current-catalogue.mjs — do not edit.
//
// The Province's ministries and the wording of their marks, in both languages, read back off the
// published outlines themselves — see scripts/recover_current_names.py. That is also how the
// French names got here, since the Province publishes them only as artwork.
//
// The wording is plain: where the line breaks go is decided by the rules in
// src/current/currentLayout.js, which reproduce 44 of the 46 published marks exactly. The other
// two carry the Province's own breaks as newlines, because their artwork disagrees with its own
// rules and the artwork wins.

export const MINISTRIES = [
${ministries.map((m) => `  ${JSON.stringify(m)}`).join(',\n')}
]

/** Marks whose breaks the rules do not reproduce, so their wording states them. */
export const BREAKS_STATED = ${JSON.stringify(exceptions.map((e) => e.key))}

/** Marks whose published breaks could not be read at all, so these are the rules' own. */
export const UNVERIFIED = ${JSON.stringify(unverified)}

export const MINISTRY_CODES = MINISTRIES.map((ministry) => ministry.code)

/** One ministry's wording, or undefined. Codes are matched case-insensitively. */
export const findMinistry = (code) => MINISTRIES
  .find((ministry) => ministry.code.toLowerCase() === String(code).toLowerCase())
`)

const stated = exceptions.length
console.log(`  catalogue   ${ministries.length} ministries, both languages   ` +
  `${((JSON.stringify(ministries).length) / 1024).toFixed(1)} KB`)
console.log(`  by rule     ${ministries.length * 2 - stated}/${ministries.length * 2} marks break exactly as published`)
for (const e of exceptions) {
  console.log(`  states its own breaks: ${e.key}`)
  console.log(`      published ${JSON.stringify(e.published)}`)
  console.log(`      by rule   ${JSON.stringify(e.byRule)}`)
}
if (unverified.length) console.log(`  breaks never recoverable: ${unverified.join(', ')}`)
console.log('  → src/current/ministries.js')
