def load(path):
    return json.loads(Path(path).read_text())


def save(path, value, pretty=False):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2 if pretty else None,
                                    separators=None if pretty else (",", ":")) + "\n")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def retrieve(url, path):
    with urllib.request.urlopen(url, timeout=90) as response:
        Path(path).write_bytes(response.read())


def project(geom):
    return shapely.make_valid(shapely.transform(shape(geom), TO_METRES.transform, interleaved=False))


def rounded(value):
    if isinstance(value, (tuple, list)):
        return [rounded(x) for x in value]
    return round(float(value), 6)


def simplify_display(geom, metres):
    projected = project(geom)
    simplified = shapely.simplify(projected, metres, preserve_topology=True)
    result = shapely.transform(simplified, TO_WGS84.transform, interleaved=False)
    obj = mapping(result)
    obj["coordinates"] = rounded(obj["coordinates"])
    if not shape(obj).is_valid:
        obj = mapping(result)
    return obj


def get_code_crosswalk():
    """Extract only the three explicitly labelled crosswalk pages."""
    path = BASE / "lha-profile-greater-nanaimo_2019.pdf"
    document = fitz.open(path)
    rows = []
    for page_no in (75, 76, 77):
        for line in document[page_no - 1].get_text("text", sort=True).splitlines():
            match = re.search(r"\b(\d{3})\s+(.+?)\s{2,}(\d{3})\s+(.+)$", line)
            if match:
                old, old_name, new, new_name = match.groups()
                rows.append({"oldCode": old, "oldNameExtracted": old_name.strip(),
                             "newCode": new, "newNameExtracted": new_name.strip(),
                             "pdfPage": page_no})
    assert len(rows) == 89 and len({x["newCode"] for x in rows}) == 89, len(rows)
    result = {
        "title": "Crosswalk of Old (1997) to New (2018) LHA Names and Numbers",
        "publisher": "BC Ministry of Health, Health Sector Information, Analysis and Reporting Division",
        "host": "Divisions of Family Practice",
        "sourceUrl": PROFILE_URL,
        "sourcePdfPages": [75, 76, 77],
        "sourcePrintedPages": [73, 74, 75],
        "sourceSha256": sha(path),
        "limitation": "This is a code/name correspondence in a 2019 report. The label 1997 identifies the old coding scheme; it does not certify that every listed subdivision existed with identical geometry in calendar 1997.",
        "rows": rows,
    }
    save(RESEARCH / "lha-code-crosswalk-1997-scheme-to-2018.json", result, True)
    return {x["newCode"]: x for x in rows}


def build_matches(index):
    """Join reviewed candidates to the original map labels, retaining identity gaps."""
    by_key = {(r["mapId"], r["sourceLegendNumber"]): r for r in CANDIDATE_RECORDS}
    assert len(by_key) == len(CANDIDATE_RECORDS) == 52
    result = []
    for record in index["records"]:
        key = record["mapId"], record["sourceLegendNumber"]
        candidate = by_key[key]
        assert candidate["bodyId"] == record["repoBodyId"], key
        assert candidate["sourceLabel"] == record["sourceLegendLabel"], key
        result.append(json.loads(json.dumps(candidate)))
    assert len(result) == 52
    return result


def audit_current():
    """Compare stored PGMaps geometry with full official current geometry."""
    for layer, (filename, code_field, name_field, _) in LAYER_INFO.items():
        pg = load(BASE / ("pgmaps-" + filename + ".json"))
        official = load(BASE / ("current-" + layer + ".geojson"))
        by_code = {x["properties"][code_field]: x for x in official["features"]}
        result = []
        for feature in pg["features"]:
            props = feature["properties"]
            other = by_code[props[code_field]]
            a, b = project(feature["geometry"]), project(other["geometry"])
            intersect = a.intersection(b).area
            union = a.area + b.area - intersect
            result.append({"code": props[code_field], "name": props[name_field],
                           "iou": intersect / union,
                           "symmetricDifferenceKm2": (union - intersect) / 1e6,
                           "referenceAreaKm2": b.area / 1e6,
                           "propertiesMatch": props == other["properties"]})
        save(BASE / ("pgmaps-vs-official-current-" + layer + ".json"), result, True)


def main():
    global BASE, PUBLIC, RESEARCH
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--map-index", type=Path, default=RESEARCH / "map-area-index.json")
    parser.add_argument("--cache-dir", type=Path, default=BASE, help="Public source downloads and audit cache")
    parser.add_argument("--output-dir", type=Path, default=PUBLIC, help="Public manifest and display GeoJSON")
    parser.add_argument("--research-dir", type=Path, default=RESEARCH, help="Extracted crosswalk and audit details")
    parser.add_argument("--fetch", action="store_true")
    parser.add_argument("--audit-current", action="store_true")
    parser.add_argument("--tolerance-metres", type=float, default=200)
    args = parser.parse_args()
    BASE, PUBLIC, RESEARCH = args.cache_dir, args.output_dir, args.research_dir
    for directory in (BASE, PUBLIC, RESEARCH):
        directory.mkdir(parents=True, exist_ok=True)
    if args.fetch:
        retrieve(PGMAPS + "index.json", BASE / "pgmaps-index.json")
        retrieve(PROFILE_URL, BASE / "lha-profile-greater-nanaimo_2019.pdf")
        for layer, (filename, _, _, typename) in LAYER_INFO.items():
            retrieve(PGMAPS + "simplified/" + filename + ".json", BASE / ("pgmaps-" + filename + ".json"))
            url = "https://openmaps.gov.bc.ca/geo/pub/ows?" + urllib.parse.urlencode({"service": "WFS", "version": "2.0.0", "request": "GetFeature", "typeNames": "pub:" + typename, "outputFormat": "application/json", "srsName": "EPSG:4326"})
            retrieve(url, BASE / ("current-" + layer + ".geojson"))
    if args.audit_current:
        audit_current()
    crosswalk = get_code_crosswalk()
    datasets, audit_summary = {}, {}
    for layer, (filename, code_field, name_field, _) in LAYER_INFO.items():
        source_path = BASE / ("pgmaps-" + filename + ".json")
        source = load(source_path)
        output_features = []
        for feature in source["features"]:
            p = feature["properties"]
            code = str(p[code_field])
            props = {"id": layer + "-" + code, "code": code, "name": p[name_field], "layer": layer,
                     "geometryStatus": "modern-pgmaps-comparison", "sourceId": "pgmaps"}
            if layer != "ha":
                props.update({"haCode": p["HLTH_AUTHORITY_CODE"], "haName": p["HLTH_AUTHORITY_NAME"]})
            if layer == "lha":
                props.update({"hsdaCode": p["HLTH_SERVICE_DLVR_AREA_CODE"], "hsdaName": p["HLTH_SERVICE_DLVR_AREA_NAME"],
                              "oldLhaCode": crosswalk[code]["oldCode"], "codeCrosswalkSourceId": "lha-crosswalk"})
            geom = simplify_display(feature["geometry"], args.tolerance_metres)
            output_features.append({"type": "Feature", "id": props["id"], "properties": props, "geometry": geom})
        output_name = "display-" + layer + ".geojson"
        output = {"type": "FeatureCollection", "metadata": {
            "sourceUrl": PGMAPS + "simplified/" + filename + ".json", "sourceSha256": sha(source_path),
            "sourceMetadata": source.get("metadata"), "coordinateSystem": "EPSG:4326", "workingCRS": "EPSG:3005",
            "displaySimplificationMetres": args.tolerance_metres, "displaySimplificationMethod": "Douglas-Peucker, preserve_topology per feature",
            "sharedBoundaryTopology": "Not asserted after additional display simplification; small inter-feature seams may occur. Original PGMaps snapshots remain the comparison inputs.",
            "historicalGeometry": False,
        }, "features": output_features}
        save(PUBLIC / output_name, output)
        datasets[layer] = {"file": output_name, "featureCount": len(output_features), "sourceId": "pgmaps", "label": {"lha": "Modern local health areas", "hsda": "Modern health service delivery areas", "ha": "Modern geographic health authorities"}[layer], "geometryStatus": "modern-pgmaps-comparison", "originalVintage": "not declared in the PGMaps snapshot", "officialReferenceConfiguration": "2022", "displayToleranceMetres": args.tolerance_metres, "sha256": sha(PUBLIC / output_name)}
        audit_path = BASE / ("pgmaps-vs-official-current-" + layer + ".json")
        if audit_path.exists():
            records = load(audit_path)
            save(RESEARCH / audit_path.name, records, True)
            audit_summary[layer] = {"comparison": "Existing PGMaps vs current official BC WFS; not a historical validation", "file": audit_path.name, "featureCount": len(records), "allPropertiesMatch": all(r["propertiesMatch"] for r in records), "minIou": min(r["iou"] for r in records), "maxIou": max(r["iou"] for r in records)}
    matches = build_matches(load(args.map_index))
    valid_codes = {f["properties"]["code"] for f in load(PUBLIC / "display-lha.geojson")["features"]}
    for match in matches:
        assert set(match["candidateLhaCodes"]) <= valid_codes, match
        assert not match["boundaryIdentityVerified"]
        assert not match["historicalOverlapMeasured"]
    regional = [m for m in matches if m["category"] != "community-health-councils"]
    used = [code for m in regional for code in m["candidateLhaCodes"]]
    assert len(used) == len(set(used)) == 88 and set(used) == valid_codes - {"518"}
    result = {"schemaVersion": 1, "preparedOn": "2026-10-31", "sources": SOURCE_RECORDS, "datasets": datasets,
              "bodyMatches": matches, "currentDataAudit": audit_summary,
              "historicalGeometryStatus": "No independently reusable georeferenced 1997 administrative geometry was acquired; no historical area-overlap scores are claimed.",
              "limitations": LIMITATIONS}
    save(PUBLIC / "boundary-comparison.json", result, True)
    print(json.dumps({"displayFiles": {k: {"features": v["featureCount"], "bytes": (PUBLIC / v["file"]).stat().st_size} for k, v in datasets.items()}, "bodyMatchCount": len(matches), "regionalCandidateLhas": len(used), "historicalMatchesClaimed": 0}, indent=2))


