#!/usr/bin/env python3
"""Build source-labelled offline PGMaps boundary layers and historical candidates.

The historical candidates are modern polygons selected from documentary clues.
They are not historical geometries. No historical IoU or exact legal-boundary
match is assigned. audit_current compares PGMaps with the current BC WFS only.

Dependencies: shapely>=2.1, pyproj, pymupdf. Install into your Python environment:
  python -m pip install shapely pyproj pymupdf
Usage from the repository root:
  python scripts/build_health_boundary_comparison.py --fetch --audit-current
  python scripts/build_health_boundary_comparison.py --cache-dir /path/to/stored/sources

Defaults: public/health-geography for the manifest and GeoJSON;
research/health-geography for the crosswalk, audit details and map-area-index.json.
Large downloads remain in a temporary cache, configurable with --cache-dir.
No historical GIS is fetched. Candidate records preserve the reviewed source
relationships and caveats; they are not generated by spatial similarity.
"""
