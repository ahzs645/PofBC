// Builds src/ministries/history.js from the BC ministry-history dataset.
//
// Three of the four identities here are historical, and the ministry list was not: it held the 27
// that exist today, so the only names you could put on a 1986 flag lockup were ones that did not
// exist in 1986. This brings in the ones that did.
//
// What is taken is names and years — facts about which ministries existed when, and which was
// renamed into which. The diagram those facts were read out of is not taken, and neither is
// anything else in the package.
//
// Run with the extracted package's path:
//
//   MINISTRY_HISTORY_SOURCE=~/Downloads/bc-ministry-history-v2.0.0 npm run build:ministry-history
//
// The output is committed, because it is a fixed historical snapshot rather than something that
// re-derives per machine — unlike the font builds, whose output is the licensed typeface itself.

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SOURCE = process.env.MINISTRY_HISTORY_SOURCE

if (!SOURCE) {
  console.error('MINISTRY_HISTORY_SOURCE is not set — point it at the extracted dataset directory.')
  process.exit(1)
}

const OUT = resolve('src/ministries/history.js')

const data = JSON.parse(readFileSync(resolve(SOURCE, 'data/ministry-history.json'), 'utf8'))

/**
 * The organisation records, as name and years.
 *
 * `organisation` is the dataset's kind for a body that existed; the other kinds are the drawing's
 * own furniture — headings, year labels, premiers, annotations — and are not ministries.
 */
const episodes = data.nodes
  .filter((node) => node.kind === 'organisation' && node.name)
  .map((node) => ({
    name: node.name,
    from: node.start_year ?? null,
    to: node.end_year ?? null
  }))
  .filter((episode) => episode.from || episode.to)
  .sort((a, b) => (a.from ?? 0) - (b.from ?? 0) || a.name.localeCompare(b.name))

/**
 * Which body was renamed or continued into which.
 *
 * Only `renamed_or_continued`, and only where the dataset marks the link as belonging in a
 * lineage. The other relation it carries — "some functions transferred" — is not a rename: chained
 * up it would connect nearly everything to nearly everything, and reporting that a ministry
 * "became" an unrelated one would be worse than reporting nothing.
 */
const renames = data.edges
  .filter((edge) => edge.relation_type === 'renamed_or_continued' && edge.include_in_lineage)
  .filter((edge) => edge.from_name && edge.to_name && edge.from_name !== edge.to_name)
  .map((edge) => [edge.from_name, edge.to_name])

const seen = new Set()
const unique = renames.filter(([from, to]) => {
  const key = `${from}\u0000${to}`
  if (seen.has(key)) return false
  seen.add(key)
  return true
})

const { source, release } = data
const snapshot = source.last_revised ?? release?.date ?? 'unknown'

const lines = [
  `// Generated by scripts/build-ministry-history.mjs — do not edit.`,
  `//`,
  `// Which ministries of the Government of British Columbia existed when, and which was renamed`,
  `// into which. Names and years only: the drawing these were read out of is not reproduced here.`,
  `//`,
  `// Source: "${source.file}" — the BC Archives ministry history diagram by ${source.creator},`,
  `// created ${source.created}, last revised ${source.last_revised}.`,
  `// ${source.official_pdf_url}`,
  `//`,
  `// Facts about the machinery of government are public record, and that is what is taken. The`,
  `// original diagram retains its own rights, and nothing here is endorsed by BC Archives.`,
  `//`,
  `// It is a snapshot to ${snapshot}, not a current directory — the list in ministries.js is what`,
  `// speaks for today. The dataset's own review notes two unresolved points: the 1978/1979`,
  `// Environment boundary, and reconstructed attachments for Industries and Labour/Finance whose`,
  `// legal histories were not independently verified.`,
  ``,
  `/** Every ministry episode: a name, and the years it ran. \`to: null\` means it had not ended. */`,
  `export const EPISODES = [`,
  ...episodes.map((e) => `  { name: ${JSON.stringify(e.name)}, from: ${e.from}, to: ${e.to} },`),
  `]`,
  ``,
  `/** Renamed or continued into. Transfers of function are deliberately not included. */`,
  `export const RENAMES = [`,
  ...unique.map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`),
  `]`,
  ``
]

writeFileSync(OUT, lines.join('\n'))

const span = [
  Math.min(...episodes.map((e) => e.from ?? Infinity)),
  Math.max(...episodes.map((e) => e.to ?? 0))
]
console.log(`  ministry history  ${episodes.length} episodes ${span[0]}–${span[1]}, ` +
  `${unique.length} renames  ${(Buffer.byteLength(lines.join('\n')) / 1024).toFixed(1)} KB`)
console.log(`  → ${OUT}`)
