import { writeFileSync } from 'node:fs'
import { allCollectedAssets } from '../src/gallery/collectedBodies.js'
import { collectedVectorVariants, galleryVectorTreatments } from './collected-vector-variants.mjs'

const assets = new Map(allCollectedAssets().map((asset) => [asset.id, asset]))
const variants = {}
for (const [id, treatment] of Object.entries(galleryVectorTreatments)) {
  const asset = assets.get(id)
  if (!asset?.isVector || asset.format !== 'svg' || asset.containsRaster) throw new Error(`Missing SVG master: ${id}`)
  const versions = collectedVectorVariants(asset, { treatment })
  const source = variants[id] ??= { overrides: {}, versions: [] }
  source.overrides.versionLabel = treatment.originalLabel
  source.versions = versions
  const designId = asset.variantOf ?? id
  const design = variants[designId] ??= { overrides: {}, versions: [] }
  if (treatment.designLabel) design.overrides.designLabel = treatment.designLabel
  if (treatment.preferred) {
    const preferred = `${id}-${treatment.preferred}`
    if (!versions.some((version) => version.id === preferred)) throw new Error(`Missing preferred version: ${preferred}`)
    design.overrides[asset.reconstruction ? 'preferredReconstruction' : 'preferredVector'] = preferred
  }
}

writeFileSync(new URL('../src/gallery/collectedVectorVariants.js', import.meta.url),
  '// Generated by scripts/build-gallery-vector-variants.mjs from reviewed source SVGs.\n' +
  `export const COLLECTED_VECTOR_VARIANTS = ${JSON.stringify(variants, null, 2)}\n`)
