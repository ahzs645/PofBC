// The bodies the gallery is collecting marks for: every Crown corporation and health authority the
// government atlas holds, today's and former, with the years each stood.
//
// The gallery is a lazy chunk of its own and the atlas's history is close to a megabyte, so the
// list is written out small rather than imported: src/gallery/collectingData.js. A test checks it
// against the atlas, so a rebuild of the government data that adds a body fails until this is run.
//
// Run: npm run build:collecting

import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { collectingFrom } from '../src/gallery/collectingSource.js'
import { CURRENT_BODIES } from '../src/government/currentData.js'
import { HISTORICAL_BODIES } from '../src/government/historyData.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bodies = collectingFrom(CURRENT_BODIES, HISTORICAL_BODIES)

writeFileSync(resolve(root, 'src/gallery/collectingData.js'), `// Generated by scripts/build-collecting.mjs — do not edit.
//
// Every Crown corporation and health authority in the government atlas, today's first, for the
// gallery's collecting shelf: id, name, kind, the years it stood, and whether it stands today.

export const COLLECTING = [
${bodies.map((body) => `  ${JSON.stringify(body)}`).join(',\n')}
]
`)
console.log(`Wrote ${bodies.length} bodies to src/gallery/collectingData.js`)
