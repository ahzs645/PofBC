def norm(s):
    return ' '.join(s.split())


def money(s):
    s = s.strip().replace('$','')
    if s in ['','-','—','–']:
        return None
    # These commas/periods are OCR punctuation after an integer cell, never cents.
    s=s.rstrip(',.')
    if not re.fullmatch(r'\(?-?[\d,]+\)?',s):
        raise ValueError(('unread OCR amount',s))
    return -int(s[1:-1].replace(',','')) if s.startswith('(') else int(s.replace(',',''))


def words_from_tsv(text,scale):
    words=[]
    with io.StringIO(text) as f:
        for w in csv.DictReader(f,delimiter='\t',quoting=csv.QUOTE_NONE):
            if w['level']=='5' and norm(w['text']):
                x,y,b,h=[float(w[k])/scale for k in ['left','top','width','height']]
                words.append({'text':w['text'],'bbox':[x,y,x+b,y+h],'cy':y+h/2,'conf':float(w['conf'])})
    return words


def tsv_words(p,scale):
    return words_from_tsv(p.read_text(),scale)


def parse(words,pn):
    top,bottom=130,355.5 if pn==42 else 752
    paywords=[w for w in words if 430<w['bbox'][0] and w['bbox'][2]<480 and top<w['cy']<bottom]
    rows=[]
    for a in sorted(paywords,key=lambda w:w['cy']):
        try:pay=money(a['text'])
        except ValueError:continue
        if pay is None:continue
        cy=a['cy'];same=[w for w in words if abs(w['cy']-cy)<3]
        fields=[];receipts=[]
        for xmin,xmax in [(0,190),(190,430),(430,480),(480,600)]:
            ws=sorted([w for w in same if xmin<=w['bbox'][0]<xmax],key=lambda w:w['bbox'][0])
            fields.append(norm(' '.join(w['text'] for w in ws)));receipts.append(ws)
        name,pos,salary,expense=fields
        if not name:raise ValueError(('missing OCR name',pn,cy,fields))
        rows.append({'pdfPage':pn,'y':round(cy,3),'cells':fields,'amounts':[money(salary),money(expense)],'wordEvidence':receipts})
    return rows


def read_pass(number):
    rows=[]
    for pn in PAGES:
        p=CACHE/(f'langara-2023-24-ocr-p{pn}.tsv' if number==1 else f'langara-independent-ocr/p{pn}-4x-psm4.tsv')
        rows+=parse(tsv_words(p,3 if number==1 else 4),pn)
    return rows


def paths(number,pn):
    return (CACHE/f'langara-2023-24-ocr-p{pn}') if number==1 else (CACHE/f'langara-independent-ocr/p{pn}-4x-psm4')


def ensure_ocr():
    """Exactly one Tesseract child at a time, with both OpenMP limits set."""
    doc=fitz.open(PDF)
    env=dict(os.environ,OMP_THREAD_LIMIT='1',OMP_NUM_THREADS='1')
    for number,scale,psm in [(1,3,6),(2,4,4)]:
        for pn in PAGES:
            stem=paths(number,pn)
            if stem.with_suffix('.tsv').exists():continue
            stem.parent.mkdir(parents=True,exist_ok=True)
            doc[pn-1].get_pixmap(matrix=fitz.Matrix(scale,scale),alpha=False).save(stem.with_suffix('.png'))
            subprocess.run(['tesseract',str(stem.with_suffix('.png')),str(stem),'--psm',str(psm),'--oem','1','-l','eng','txt','tsv'],env=env,check=True,capture_output=True,timeout=180)


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')


def write_gzip(path,data):
    raw=(json.dumps(data,ensure_ascii=False,separators=(',',':'))+'\n').encode()
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_bytes(gzip.compress(raw,mtime=0))
    return sha(path),hashlib.sha256(raw).hexdigest()


def resolved_rows(a,b):
    assert len(a)==len(b)==891
    assert Counter(r['pdfPage'] for r in a)==Counter({**{p:86 for p in range(32,42)},42:31})
    assert Counter(r['pdfPage'] for r in a)==Counter(r['pdfPage'] for r in b)
    result,corrections=[],[]
    for rn,(aa,bb) in enumerate(zip(a,b),1):
        assert aa['pdfPage']==bb['pdfPage'] and abs(aa['y']-bb['y'])<1
        assert aa['amounts']==bb['amounts'],('monetary OCR disagreement',rn,aa,bb)
        cells=bb['cells'][:2]
        for col,value in TEXT_FIXES.get(rn,{}).items():cells[col]=value
        for col,field in enumerate(['name','position']):
            if aa['cells'][col]!=bb['cells'][col] or cells[col]!=bb['cells'][col]:
                corrections.append({'rowNumber':rn,'pdfPage':bb['pdfPage'],'field':field,
                                    'ocrPass1':aa['cells'][col],'ocrPass2':bb['cells'][col],'sourcePixels':cells[col],
                                    'basis':'Literal complete source row visually reviewed; OCR punctuation/case artifact corrected. Row 880 enlarged name crop confirms Zanzerl, Heather.' if rn==880 else 'Literal complete source row visually reviewed; OCR punctuation/case artifact corrected.'})
        result.append(['langara-college',cells[0],cells[1],bb['amounts'][0],bb['amounts'][1],bb['pdfPage']])
    assert [sum(r[j] or 0 for r in result) for j in [3,4]]==[94671610,2754209]
    assert sum(r[4] is None for r in result)==19
    return result,corrections


