// The serif BC Hydro's lettering is set in, as a table of numbers and outlines.
//
// The historical signature's typeface was never recovered. What the reconstruction was fitted
// against is Nimbus Roman, URW's Times; this uses TeX Gyre Termes, the GUST's free derivative of
// that same Nimbus Roman, which keeps its widths to the unit. Termes is distributed under the
// LaTeX Project Public License, so unlike Helvetica and Adobe Garamond — which this project only
// ever builds per machine — its outlines can be committed, and every BC Hydro mark draws the same
// on any machine without a font installed at all.
//
// Out comes src/hydro/serif.js: for each character, its advance, its ink box and its outline, in a
// 1000-unit em with y running downward as SVG measures it; the kerning between every pair that has
// any; and the cap and x-heights the identification signs are laid out in.
//
// The committed table is the source the app uses. Regenerating it needs the font:
//
//   curl -L -o tmp/fonts/texgyretermes-regular.otf \
//     https://mirrors.ctan.org/fonts/tex-gyre/opentype/texgyretermes-regular.otf
//   npm run build:hydro-serif        # or HYDRO_SERIF_SOURCE=/path/to/texgyretermes-regular.otf

import * as fontkit from 'fontkit'
import { existsSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = process.env.HYDRO_SERIF_SOURCE || resolve(root, 'tmp/fonts/texgyretermes-regular.otf')
const target = resolve(root, 'src/hydro/serif.js')

if (!existsSync(SOURCE)) {
  console.error(
    `\nCould not find TeX Gyre Termes at ${SOURCE}.\n` +
    'src/hydro/serif.js is committed, so nothing needs this unless the table is being rebuilt.\n' +
    'To rebuild it, fetch the font from CTAN first:\n\n' +
    '    curl -L -o tmp/fonts/texgyretermes-regular.otf \\\n' +
    '      https://mirrors.ctan.org/fonts/tex-gyre/opentype/texgyretermes-regular.otf\n'
  )
  process.exit(1)
}

const font = fontkit.openSync(SOURCE)
const scale = 1000 / font.unitsPerEm
const round = (value) => Math.round(value * scale * 10) / 10

const range = (from, to) => Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i))

// Printable ASCII and Latin-1 cover facility names and any wording a sign is likely to carry; the
// typographer's punctuation is what a word processor substitutes into them.
const CHARSET = [...range(0x20, 0x7e), ...range(0xa0, 0xff), ...'‐–—‘’“”…•']

const glyphs = {}
for (const character of CHARSET) {
  const glyph = font.glyphForCodePoint(character.codePointAt(0))
  if (!glyph || glyph.id === 0) continue
  const { minX, minY, maxX, maxY } = glyph.bbox
  const inked = glyph.path.commands.length > 0
  glyphs[character] = {
    w: round(glyph.advanceWidth),
    // The ink box as a canvas reports it: left and right from the pen, top and bottom from the
    // baseline, both measured downward. A glyph with no ink has none.
    ...(inked ? { box: [round(minX), round(-maxY), round(maxX), round(-minY)] } : {}),
    ...(inked ? { d: glyph.path.scale(scale, -scale).toSVG().replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10)) } : {})
  }
}

// Kerning is whatever the font's layout engine applies between two characters, measured by
// setting the pair and comparing it with the two set apart — the same question the original
// studio asked a canvas.
const letters = Object.keys(glyphs).filter((character) => character !== ' ')
const kerning = {}
for (const left of letters) {
  for (const right of letters) {
    const pair = font.layout(left + right)
    if (pair.glyphs.length !== 2) continue
    const kern = pair.positions[0].xAdvance - pair.glyphs[0].advanceWidth
    if (kern) kerning[left + right] = round(kern)
  }
}

const verticals = {
  capHeight: -glyphs.H.box[1],
  xHeight: -glyphs.x.box[1]
}

writeFileSync(target, `// Generated by scripts/build-hydro-serif.mjs — do not edit.
//
// TeX Gyre Termes Regular (c) 2006–2009 B. Jackowski and J.M. Nowacki, on behalf of TeX Users
// Groups — a derivative of URW's Nimbus Roman No9 L, distributed under the LaTeX Project Public
// License 1.3c (GUST Font License). The substitute the historical BC Hydro signatures are set in;
// their own typeface was never recovered.
//
// Units are 1/1000 em. Boxes are [left, top, right, bottom] from the pen, y downward; outlines are
// SVG path data in the same frame, baseline at zero.

export const SERIF_FAMILY = 'TeX Gyre Termes'
export const CAP_HEIGHT = ${verticals.capHeight}
export const X_HEIGHT = ${verticals.xHeight}

export const GLYPHS = {
${Object.entries(glyphs).map(([character, glyph]) => `  ${JSON.stringify(character)}: ${JSON.stringify(glyph)}`).join(',\n')}
}

/** Pair kerning, keyed by the two characters. */
export const KERNING = ${JSON.stringify(kerning)}
`)

console.log(`  hydro serif ${Object.keys(glyphs).length} glyphs, ${Object.keys(kerning).length} kerning pairs → src/hydro/serif.js`)
