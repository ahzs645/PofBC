// The government panel is a projection of accepted employer records. This is shared by the full
// salary build and the bounded body-link rebuild, so connecting an employer never reimports pay.
import { employerCurrency } from '../../src/salaries/recordAnnotations.js'
import { median, sumMoney } from './salary-data.mjs'

export const governmentSalaryPeriods = ({ info, exported, coverage, years, sources }) => {
  if (!info.body) return []
  const labels = years.map((entry) => entry.label)
  return years.flatMap((year, at) => {
    const subset = exported.filter((row) => row[4] === at)
    if (!subset.length) return []
    const rows = subset.map((row) => [row[0], row[1], row[2], row[3], row[5], row[6]])
    const cad = subset.filter((row) => employerCurrency(row, info.slug, labels, sources) === 'CAD')
    const details = coverage[at]
    return [{
      slug: year.slug,
      data: { ...details, year: year.label, agencies: info.names, rows },
      totals: {
        count: rows.length, total: sumMoney(cad.map((row) => row[2])), median: median(cad.map((row) => row[2])),
        max: cad.length ? Math.max(...cad.map((row) => row[2])) : null, agencies: info.names,
        sourceIds: details.sourceIds, scope: details.scope, notes: details.notes,
        periodStart: details.periodStart, periodEnd: details.periodEnd, threshold: details.threshold, duplicateRows: details.duplicateRows,
        ...(cad.length !== subset.length ? { comparisonCurrency: 'CAD', comparableRecords: cad.length, nonCadRecords: subset.length - cad.length } : {})
      }
    }]
  })
}

export const salaryIndexModule = (index) =>
  `// Generated by scripts/build-salaries.mjs — do not edit.\n` +
  `// Counts and totals describe the imported disclosure rows, not a full workforce census.\n` +
  `export const SALARY_YEARS = ${JSON.stringify(index.years)}\n` +
  `export const SALARY_INDEX = ${JSON.stringify(index.bodies)}\n` +
  `export const SALARY_SOURCES = ${JSON.stringify(index.sources)}\n` +
  `export const SALARY_COVERAGE = ${JSON.stringify(index.coverage)}\n` +
  `export const SALARY_EMPLOYERS = ${JSON.stringify(index.employers)}\n`
