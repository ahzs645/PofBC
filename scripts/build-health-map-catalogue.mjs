// Preserve original map labels while linking them to institutional IDs.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { buildHealthResearch, researchMarkdown } from './health-map-research.mjs'
const root = new URL('../', import.meta.url)
const read = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'))
const [index, lineage, earlier, comparison, evidencePlan] = await Promise.all([
  read('research/health-geography/map-area-index.json'),
  read('research/history/bodies-health-lineage.json'),
  read('research/health-geography/1995-twenty-board-boundaries.json'),
  read('public/health-geography/boundary-comparison.json'),
  read('research/health-geography/evidence-plan.json')
])
const bodyById = new Map(lineage.records.map((body) => [body.id, body]))
const ids = { 3: 'boards', 4: 'councils', 5: 'societies' }
const assets = { 3: 'regional-health-boards', 4: 'community-health-councils', 5: 'community-health-services-societies' }
const maps = index.maps.map((map) => ({
  id: ids[map.exhibit], title: map.title, sourceUrl: map.sourcePageUrl,
  sourceTitle: `BC Auditor General, 1997/98 Report 3, exhibit ${map.exhibit}`,
  printedPage: map.printedPage, pdfPage: map.pdfPage,
  asset: `maps/${assets[map.exhibit]}-1997-98.svg`, credit: map.cartographyCredit,
  dateLabel: '1997 restructuring · published 1998', viewBox: '0 0 612 792',
}))
maps.unshift({
  id: 'regions-2000', title: 'Twenty statistical health regions',
  sourceTitle: 'Statistics Canada, Health Indicators, April 2001',
  sourceUrl: 'https://www150.statcan.gc.ca/n1/pub/82-221-x/00401/images/pdf/4195184-eng.pdf',
  asset: 'maps/statcan-bc-health-regions-2000-map.svg',
  credit: 'Source: Statistics Canada, Health Indicators, April 2001. Reproduced and distributed on an "as is" basis with the permission of Statistics Canada.',
  dateLabel: 'Published April 2001', viewBox: '0 0 612 792',
})
const areas = index.records.map((record) => {
  const body = record.repoBodyId ? bodyById.get(record.repoBodyId) : null
  if (record.repoBodyId && !body) throw new Error(`Unknown body: ${record.repoBodyId}`)
  return {
    id: record.repoBodyId ?? 'nisgaa-source-area', bodyId: record.repoBodyId,
    name: record.repoBodyName ?? record.sourceLegendLabel,
    sourceLabel: record.sourceLegendLabel, number: record.sourceLegendNumber,
    mapId: ids[record.exhibit], sourceUrl: record.sourcePageUrl,
    identityConfirmed: record.identityMatchConfirmed, identityStatus: record.matchStatus,
    notes: record.notes, relatedBodyIds: record.relatedRepoBodyIds,
    established: body?.established ?? null, ended: body?.ended ?? null,
    successorIds: [body?.becameId, ...(body?.serviceSuccessorIds ?? [])].filter(Boolean),
    legalDefinition: record.supportingBoundaryDefinition ?? null,
  }
})
if (new Set(areas.map((area) => area.id)).size !== areas.length) throw new Error('Duplicate map area ID')
const catalogue = { schemaVersion: 1, preparedOn: '2026-10-31', maps, areas,
  earlierBoards: earlier.records, note: 'Names matched to sources; modern polygons and historical legal territories are distinct evidence.' }
await mkdir(new URL('src/health/', root), { recursive: true })
await mkdir(new URL('public/health-geography/', root), { recursive: true })
await writeFile(new URL('src/health/healthAreas.generated.js', root), '// Generated by scripts/build-health-map-catalogue.mjs; edit the research inputs.\n' + `export const HEALTH_CATALOGUE = ${JSON.stringify(catalogue, null, 2)}\n`)
await writeFile(new URL('public/health-geography/catalogue.json', root), JSON.stringify(catalogue, null, 2) + '\n')
const research = buildHealthResearch(catalogue, comparison, evidencePlan)
await writeFile(new URL('src/health/healthResearch.generated.js', root), '// Generated by scripts/build-health-map-catalogue.mjs; edit the research inputs.\n' + `export const HEALTH_RESEARCH = ${JSON.stringify(research, null, 2)}\n`)
await writeFile(new URL('public/health-geography/research-plan.json', root), JSON.stringify(research, null, 2) + '\n')
const report = researchMarkdown(research)
await writeFile(new URL('research/health-geography/records-to-obtain.md', root), report)
await writeFile(new URL('public/health-geography/records-to-obtain.md', root), report)
console.log(`Health map catalogue: ${areas.length} source areas, ${areas.filter((area) => area.identityConfirmed).length} institutional matches`)
console.log(`Health research: ${research.coverage.analysisItems} source-review tasks, ${research.coverage.recordsItems} records targets; all ${research.coverage.sourceAreas} areas covered`)
