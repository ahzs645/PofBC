// Extends the ministry-mark alphabet with the letters the Province never published.
//
// src/current/nameGlyphs.js holds the letterforms recovered from the Province's own marks. That is
// every letter their 23 ministry names use, and it is committed — so a clone, CI and the deployed
// site can draw every official mark without any font at all.
//
// It is not the whole alphabet, though. Wording of your own can want a B, a K, a digit, a bracket.
// Those come from a licensed Adobe Garamond Pro, the serif the B.C. Visual Identity Program
// specifies, and they are gitignored: a full alphabet of outlines is the typeface however it is
// stored. Without the font this writes an empty module and the app says which letters it cannot
// draw rather than dropping them.
//
// Runs as part of `npm run build:assets`, so it must never fail a build.

import * as fontkit from 'fontkit'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import published from '../src/current/nameGlyphs.js'
import lifted from '../src/current/liftedGlyphs.js'
import { LIGATURES } from '../src/current/nameMetrics.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const generatedDir = resolve(root, 'src/current/generated')
const target = resolve(generatedDir, 'nameGlyphsExtra.js')

// No default path, deliberately. Picking a licensed font up off the machine automatically would
// mean an ordinary `npm run build` quietly bundled it — and a deploy would publish it. Extending
// the alphabet is a decision, so it has to be stated.
const SOURCE = process.env.GARAMOND_SOURCE

const HEADER = `// Generated by scripts/build-current-extras.mjs — do not edit, and do not commit.`

mkdirSync(generatedDir, { recursive: true })

if (!SOURCE || !existsSync(SOURCE)) {
  // Only write the empty module if there is nothing there: a previous run with the font in place
  // produced something better, and a build without it should not throw that away.
  if (!existsSync(target)) {
    writeFileSync(target, `${HEADER}
//
// Empty: GARAMOND_SOURCE was not set, so the alphabet is whatever the Province's own published
// marks contain. That is the right default for anything published — these outlines are a licensed
// typeface, and a build that picked them up on its own would put them on the open web.

export default {}
`)
    console.log('  alphabet    the Province’s published letters only ' +
      '(GARAMOND_SOURCE=/path/to/AGaramondPro-Regular.otf extends it)')
  }
  process.exit(0)
}

const font = fontkit.openSync(SOURCE)
const emScale = 1000 / font.unitsPerEm
const asLetters = new Map(LIGATURES.map(([from, to]) => [to, from]))
const expand = (character) => asLetters.get(character) ?? character

const range = (from, to) => Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i))
const CHARSET = [
  ...range(0x20, 0x7e),
  ...range(0xa0, 0xff),
  ...range(0x100, 0x17f),
  ...'‐‑–—‘’“”…‹›€',
  ...LIGATURES.map(([, to]) => to)
]

const extra = {}
for (const character of CHARSET) {
  // The Province's own drawing wins wherever there is one, lifted letters included.
  if (character === ' ' || published[character] || lifted[character]) continue
  const run = font.layout(expand(character))
  if (!run.glyphs.length || run.glyphs.some((glyph) => glyph.id === 0)) continue
  const glyph = run.glyphs[0]
  if (run.glyphs.length > 1 || !glyph?.path?.commands?.length) continue
  // The alphabet's own convention: a 1000-unit em, baseline at zero, y running downward as SVG
  // measures it, so a letter drops into a <path> with a translate and a scale.
  extra[character] = glyph.path.scale(emScale, -emScale).toSVG()
}

writeFileSync(target, `${HEADER}
//
// The letters Adobe Garamond has that the Province's published marks do not, so wording of your
// own can use any of them. Rebuilt per machine from a licensed copy; src/current/nameGlyphs.js —
// the letters that *are* in the published artwork — is what ships.

export default {
${Object.entries(extra).map(([ch, d]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(d)}`).join(',\n')}
}
`)

console.log(`  alphabet    ${Object.keys(published).length + Object.keys(lifted).length} published letters + ` +
  `${Object.keys(extra).length} from the licensed font (gitignored)`)
