// Compiles source rosters and reconciliation decisions without converting observations to lifecycles.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
const root = process.env.GOVERNMENT_RESEARCH || 'research'
const read = (path) => JSON.parse(readFileSync(resolve(root, path), 'utf8'))
const files = existsSync(resolve(root, 'censuses')) ? readdirSync(resolve(root, 'censuses')).filter((n) => n.endsWith('.json')).sort() : []
const censuses = files.map((name) => read(`censuses/${name}`))
for (const census of censuses) {
  if (census.schema_version !== 'historical-census/1') throw new Error('Unknown census schema')
  for (const roster of census.rosters) {
    if (!roster.source_url || !roster.rows.every((r) => r.name_as_printed && r.locator && r.disposition)) throw new Error(`Incomplete census ${roster.id}`)
  }
}
const auditNames = ['events', 'history', 'atlas']
const imports = Object.fromEntries(auditNames.map((name) => [name, existsSync(resolve(root, `audit/${name}-import.json`)) ? read(`audit/${name}-import.json`).counts : null]))
writeFileSync('src/government/researchData.js', `// Generated by scripts/build-government-research.mjs — do not edit.\nexport const HISTORICAL_CENSUSES = ${JSON.stringify(censuses)}\nexport const IMPORT_COUNTS = ${JSON.stringify(imports)}\n`)
console.log(`${censuses.length} historical censuses, ${censuses.flatMap((c) => c.rosters).reduce((n, r) => n + r.rows.length, 0)} roster occurrences`)
