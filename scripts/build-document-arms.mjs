#!/usr/bin/env node
// Build the document-heading study from the existing plate arms and open font outlines.
// This does not trace the supplied document screenshots or assert their historical typefaces.
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { openSync } from 'fontkit'

const root = new URL('../', import.meta.url)
const sourcePath = 'artwork/stationery/grace-mccarthy/evidence/supplied-arms-fragment.txt'
const outputPath = 'src/documentArms/geometry.generated.js'
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')
const read = (path) => readFile(new URL(path, root))
const round = (value) => Math.round(value * 1000) / 1000

const fragment = await read(sourcePath)
const paths = [...fragment.toString('utf8').matchAll(/<path\s+d="([^"]+)"\s+fill="currentColor"\s+fill-rule="evenodd"><\/path>/g)]
if (paths.length !== 1 || !paths[0][1].startsWith('M555 1261') ||
    /[^MmLlHhVvCcSsQqTtAaZzEe\d\s.,+\-]/.test(paths[0][1])) {
  throw new Error('The supplied plate-study path no longer matches its documented shape. Review the source before rebuilding.')
}

const fontSpecs = {
  serif: {
    name: 'Noto Serif Bold',
    path: 'node_modules/@fontsource/noto-serif/files/noto-serif-latin-700-normal.woff',
    source: 'https://github.com/notofonts/latin-greek-cyrillic',
    package: '@fontsource/noto-serif@5.3.0',
    license: 'SIL Open Font License 1.1'
  },
  caption: {
    name: 'Barlow Condensed Bold',
    path: 'node_modules/@fontsource/barlow-condensed/files/barlow-condensed-latin-700-normal.woff',
    source: 'https://github.com/jpt/barlow',
    package: '@fontsource/barlow-condensed@5.3.0',
    license: 'SIL Open Font License 1.1'
  },
  blackletter: {
    name: 'UnifrakturMaguntia Book',
    path: 'src/documentArms/fonts/unifrakturmaguntia/UnifrakturMaguntia-Book.ttf',
    source: 'https://github.com/google/fonts/blob/main/ofl/unifrakturmaguntia/UnifrakturMaguntia-Book.ttf',
    upstreamBlob: '6429ce25445be1568534f5bd7f2b42f42fb6ff17',
    license: 'SIL Open Font License 1.1'
  }
}

const fonts = {}
const fontSources = {}
for (const [key, spec] of Object.entries(fontSpecs)) {
  const bytes = await read(spec.path)
  fonts[key] = openSync(fileURLToPath(new URL(spec.path, root)))
  fontSources[key] = { ...spec, sha256: digest(bytes) }
}

// All paths use a top-left origin and SVG's downward y-axis. The whole word is shaped first,
// preserving the font's kerning and mark positioning, before glyphs are positioned and outlined.
const outline = (font, text, capHeight) => {
  const run = font.layout(text)
  if (run.glyphs.some((glyph) => glyph.id === 0)) throw new Error(`Missing glyph in ${text}`)
  const bounds = run.bbox
  const scale = capHeight / font.capHeight
  let penX = 0
  let penY = 0
  const parts = run.glyphs.map((glyph, index) => {
    const position = run.positions[index]
    const x = penX + position.xOffset
    const y = penY + position.yOffset
    const path = glyph.path.mapPoints((px, py) => [
      round((px + x - bounds.minX) * scale),
      round((bounds.maxY - py - y) * scale)
    ]).toSVG()
    penX += position.xAdvance
    penY += position.yAdvance
    return path
  })
  return {
    text,
    width: round((bounds.maxX - bounds.minX) * scale),
    height: round((bounds.maxY - bounds.minY) * scale),
    baseline: round(bounds.maxY * scale),
    path: parts.join('')
  }
}

const lettering = {
  serifBritish: outline(fonts.serif, 'BRITISH', 132),
  serifColumbia: outline(fonts.serif, 'COLUMBIA', 132),
  government: outline(fonts.caption, 'THE GOVERNMENT OF', 57),
  province: outline(fonts.caption, 'THE PROVINCE OF BRITISH COLUMBIA', 57),
  blackletterBritish: outline(fonts.blackletter, 'British', 430),
  blackletterColumbia: outline(fonts.blackletter, 'Columbia', 430)
}

const provenance = {
  status: 'provisional-study',
  arms: {
    source: sourcePath,
    sourceSha256: digest(fragment),
    pathSha256: digest(paths[0][1]),
    naturalSize: [1146, 1283],
    origin: 'PlateForge supplied bc-crest-vector-kit lighter-detail master: vector conversion of a generated master, not a verified historical or official drawing.',
    note: 'The same path is held in the Grace McCarthy evidence package. It differs from the document engravings supplied for this study.'
  },
  fonts: fontSources,
  lettering: 'Modern open-font stand-ins, outlined for portable exports. No identification of a historical typeface is asserted.'
}

const output = '// Generated by node scripts/build-document-arms.mjs. Do not edit by hand.\n' +
  '// The generated-master arms and all lettering are provisional studies; see DOCUMENT_ARMS_SOURCE.\n' +
  `export const DOCUMENT_ARMS_SOURCE = ${JSON.stringify(provenance, null, 2)}\n\n` +
  `export const DOCUMENT_ARMS_PATH = ${JSON.stringify(paths[0][1])}\n\n` +
  `export const DOCUMENT_ARMS_LETTERING = ${JSON.stringify(lettering, null, 2)}\n`

if (process.argv.includes('--check')) {
  const existing = await read(outputPath)
  if (existing.toString('utf8') !== output) throw new Error('Document-arms geometry does not reproduce. Run node scripts/build-document-arms.mjs.')
  console.log('Document-arms geometry reproduces exactly.')
} else {
  await writeFile(new URL(outputPath, root), output)
  console.log(`Wrote ${outputPath}; arms path SHA-256 ${provenance.arms.pathSha256}`)
}
